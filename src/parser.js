import * as cheerio from 'cheerio';

export function parseDocsVersion(html) {
  const $ = cheerio.load(html);
  const text = cleanText($('.header, #titlearea, body').first().text());
  const match = text.match(/OpenTTD\s+AI\s+API\s+([^|]+?)(?=\s+(?:Main classes|Data Structure|What's new|Generated by|$))/i);
  if (match) return match[1].trim();

  const title = cleanText($('title').text());
  const titleMatch = title.match(/OpenTTD\s+AI\s+API\s+(.+?)(?:\s*:\s*|$)/i);
  return titleMatch?.[1]?.trim() || null;
}

export function discoverClassUrls(html, pageUrl) {
  const $ = cheerio.load(html);
  const urls = new Set();

  $('a[href]').each((_, element) => {
    const href = $(element).attr('href');
    const url = safeUrl(href, pageUrl);
    if (!url) return;
    const leaf = url.pathname.split('/').filter(Boolean).at(-1) ?? '';
    if (/^class[A-Za-z0-9_]+(?:\.html)?$/.test(leaf)) {
      url.hash = '';
      url.search = '';
      urls.add(url.href);
    }
  });

  return [...urls].sort();
}

export function discoverGuideUrls(html, pageUrl) {
  const $ = cheerio.load(html);
  const base = new URL(pageUrl);
  const urls = new Set();

  $('.contents a[href], .textblock a[href]').each((_, element) => {
    const href = $(element).attr('href');
    const url = safeUrl(href, pageUrl);
    if (!url || url.origin !== base.origin) return;
    if (!url.pathname.startsWith(base.pathname)) return;

    const leaf = url.pathname.split('/').filter(Boolean).at(-1) ?? '';
    if (!leaf || /^class[A-Za-z0-9_]+(?:\.html)?$/.test(leaf)) return;
    if (/^(classes|hierarchy|annotated)(?:\.html)?$/.test(leaf)) return;

    url.hash = '';
    url.search = '';
    urls.add(url.href);
  });

  return [...urls].sort();
}

export function parseClassPage(html, url) {
  const $ = cheerio.load(html);
  stripNoise($);

  const title = cleanText($('.title').first().text()) || cleanText($('title').text());
  const className = title.match(/^([A-Za-z0-9_]+)\s+Class Reference/i)?.[1]
    ?? guessClassFromUrl(url);

  if (!className) return [];

  const documents = [];
  const description = cleanText($('.contents > .textblock').first().text() || $('.textblock').first().text());
  const declarations = cleanText($('.memberdecls').first().text());

  documents.push({
    id: `class:${className}`,
    kind: 'class',
    title: `${className} Class Reference`,
    className,
    symbol: null,
    url,
    content: joinSections([
      description,
      declarations ? `Public API summary\n${declarations}` : '',
    ]),
  });

  $('.memitem').each((_, item) => {
    const memitem = $(item);
    const headingElement = memitem.prevAll('.memtitle').first();
    const heading = cleanText(headingElement.text()).replace(/^◆\s*/, '');
    const signature = cleanText(memitem.find('.memproto').first().text());
    const docs = cleanText(memitem.find('.memdoc').first().text());

    if (!heading && !signature && !docs) return;

    const symbol = extractSymbol(heading, signature);
    const anchor = headingElement.prevAll('a[id]').first().attr('id')
      ?? memitem.find('[id]').first().attr('id')
      ?? null;
    const sourceUrl = anchor ? `${url}#${anchor}` : url;
    const displayTitle = symbol ? `${className}::${symbol}` : `${className} — ${heading || 'member'}`;

    documents.push({
      id: `symbol:${className}:${symbol || slug(heading || signature)}`,
      kind: 'symbol',
      title: displayTitle,
      className,
      symbol: symbol || null,
      url: sourceUrl,
      content: joinSections([
        signature ? `Signature\n${signature}` : '',
        docs,
      ]),
    });
  });

  return dedupeById(documents);
}

export function parseGuidePage(html, url) {
  const $ = cheerio.load(html);
  stripNoise($);

  const title = cleanText($('.title').first().text()) || cleanText($('title').text()) || url;
  const content = cleanText($('.contents').first().text());
  if (!content) return null;

  return {
    id: `guide:${slug(new URL(url).pathname)}`,
    kind: 'guide',
    title,
    className: null,
    symbol: null,
    url,
    content,
  };
}

export function cleanText(value) {
  return String(value ?? '')
    .replace(/\u00a0/g, ' ')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n[ \t]+/g, '\n')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function stripNoise($) {
  $('script, style, nav, .navpath, #nav-tree, #side-nav, .footer, .header, .summary').remove();
}

function extractSymbol(heading, signature) {
  const source = heading || signature;
  const call = source.match(/(?:[A-Za-z0-9_]+::)?([~A-Za-z_][A-Za-z0-9_]*)\s*\(/);
  if (call) return call[1];

  const enumOrType = heading.match(/^([A-Za-z_][A-Za-z0-9_]*)$/);
  return enumOrType?.[1] ?? null;
}

function guessClassFromUrl(url) {
  try {
    const leaf = new URL(url).pathname.split('/').filter(Boolean).at(-1) ?? '';
    return leaf.match(/^class([A-Za-z0-9_]+)(?:\.html)?$/)?.[1] ?? null;
  } catch {
    return null;
  }
}

function safeUrl(href, base) {
  if (!href || href.startsWith('javascript:') || href.startsWith('mailto:')) return null;
  try {
    return new URL(href, base);
  } catch {
    return null;
  }
}

function joinSections(sections) {
  return sections.filter(Boolean).join('\n\n').trim();
}

function slug(value) {
  return String(value)
    .replace(/^https?:\/\//, '')
    .replace(/[^A-Za-z0-9_-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()
    .slice(0, 180) || 'page';
}

function dedupeById(documents) {
  const seen = new Set();
  return documents.filter((document) => {
    if (seen.has(document.id)) return false;
    seen.add(document.id);
    return true;
  });
}
